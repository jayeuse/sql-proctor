#!/usr/bin/env sh
set -eu

PROV_USER="${MARIADB_PROVISIONER_USER:-sql_provisioner}"
RUNNER_USER="${MARIADB_USER:-sql_runner}"
EXEC_DB="${MARIADB_DATABASE:-sql_exec}"

if [ -z "${MARIADB_PROVISIONER_PASSWORD:-}" ] || [ -z "${MARIADB_PASSWORD:-}" ]; then
  echo "MARIADB_PROVISIONER_PASSWORD and MARIADB_PASSWORD must be set." >&2
  exit 1
fi

if [ -n "${MARIADB_ROOT_PASSWORD:-}" ]; then
  MYSQL_PWD="${MARIADB_ROOT_PASSWORD}"
  export MYSQL_PWD
  DB_CMD="mariadb -uroot"
else
  DB_CMD="mariadb -uroot"
fi

# Escape single quotes for SQL string literals
esc() {
  printf '%s' "$1" | sed "s/'/''/g"
}

PROV_USER_ESC="$(esc "$PROV_USER")"
PROV_PASS_ESC="$(esc "$MARIADB_PROVISIONER_PASSWORD")"
RUNNER_USER_ESC="$(esc "$RUNNER_USER")"
RUNNER_PASS_ESC="$(esc "$MARIADB_PASSWORD")"

${DB_CMD} <<SQL
CREATE USER IF NOT EXISTS '${PROV_USER_ESC}'@'%' IDENTIFIED BY '${PROV_PASS_ESC}';
ALTER USER '${PROV_USER_ESC}'@'%' IDENTIFIED BY '${PROV_PASS_ESC}';
REVOKE ALL PRIVILEGES, GRANT OPTION FROM '${PROV_USER_ESC}'@'%';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, DROP, REFERENCES, INDEX, ALTER,
  CREATE TEMPORARY TABLES, LOCK TABLES, CREATE VIEW, SHOW VIEW, TRIGGER
  ON \`sbx_%\`.* TO '${PROV_USER_ESC}'@'%' WITH GRANT OPTION;

CREATE USER IF NOT EXISTS '${RUNNER_USER_ESC}'@'%' IDENTIFIED BY '${RUNNER_PASS_ESC}';
ALTER USER '${RUNNER_USER_ESC}'@'%' IDENTIFIED BY '${RUNNER_PASS_ESC}'
  WITH MAX_USER_CONNECTIONS 30 MAX_STATEMENT_TIME 5;
REVOKE ALL PRIVILEGES, GRANT OPTION FROM '${RUNNER_USER_ESC}'@'%';
FLUSH PRIVILEGES;
SQL
